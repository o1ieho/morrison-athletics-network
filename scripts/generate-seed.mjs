// Generates the SQL seed files from data/seed/roster.json.
//
//   supabase/seed.sql       Season, sport, the 4 MAT teams and current rosters.
//                           Safe to run on the real project (upserts).
//   supabase/demo-seed.sql  Sample opponents, games and simulated play-by-play.
//                           For local testing and demos only. Every demo row id
//                           starts with "demo-" so `delete ... like 'demo-%'`
//                           removes it cleanly.
//
// Run: npm run seed:generate

import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { simulateGame } from "./lib/simulate-game.mjs";

const root = process.cwd();
const data = JSON.parse(readFileSync(path.join(root, "data", "seed", "roster.json"), "utf8"));

function sql(value) {
  if (value === null || value === undefined) return "null";
  if (typeof value === "number" || typeof value === "boolean") return String(value);
  return `'${String(value).replaceAll("'", "''")}'`;
}

function slugify(value) {
  return String(value)
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/(^-|-$)/g, "");
}

function values(rows) {
  return rows.map((row) => `  (${row.map(sql).join(", ")})`).join(",\n");
}

const { season, teams, roster } = data;
const athletes = roster.map((player) => ({ ...player, id: slugify(player.name), slug: slugify(player.name) }));

