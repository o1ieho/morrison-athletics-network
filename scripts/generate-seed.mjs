const seed = [
  "-- Generated by scripts/generate-seed.mjs from data/seed/roster.json. Do not edit by hand.",
  "begin;",
  "",
  `insert into public.seasons (id, name, starts_on, ends_on, is_active) values\n${values([
    [season.id, season.name, season.startsOn, season.endsOn, true],
  ])}\non conflict (id) do update set name = excluded.name, starts_on = excluded.starts_on, ends_on = excluded.ends_on, is_active = excluded.is_active;`,
  "",
  "insert into public.sports (id, slug, name) values ('basketball', 'basketball', 'Basketball')\non conflict (id) do nothing;",
  "",
  `insert into public.teams (id, sport_id, slug, name, gender, level) values\n${values(
    teams.map((team) => [team.id, "basketball", team.slug, team.name, team.gender, team.level]),
  )}\non conflict (id) do update set slug = excluded.slug, name = excluded.name, gender = excluded.gender, level = excluded.level;`,
  "",
  `insert into public.athletes (id, slug, full_name) values\n${values(
    athletes.map((athlete) => [athlete.id, athlete.slug, athlete.name]),
  )}\non conflict (id) do update set full_name = excluded.full_name;`,
  "",
  `insert into public.athlete_seasons (athlete_id, season_id, team_id, jersey_number, position, grade, height) values\n${values(
    athletes.map((athlete) => [
      athlete.id,
      season.id,
      athlete.team,
      athlete.number ?? null,
      athlete.position ?? null,
      athlete.grade ?? null,
      athlete.height ?? null,
    ]),
  )}\non conflict (athlete_id, season_id, team_id) do update set jersey_number = excluded.jersey_number, position = excluded.position, grade = excluded.grade, height = excluded.height;`,
  "",
  "commit;",
  "",
];

writeFileSync(path.join(root, "supabase", "seed.sql"), seed.join("\n"));

