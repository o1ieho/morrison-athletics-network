function startsAtSql(game) {
  const expression = `now() + interval '${game.startsIn} seconds'`;
  return game.roundToHour ? `date_trunc('hour', ${expression})` : `(${expression})`;
}

const demo = [
  "-- Generated by scripts/generate-seed.mjs. DEMO DATA ONLY: never run this on the real project.",
  "-- Remove with:",
  "--   delete from public.games where id like 'demo-%';",
  "--   delete from public.opponents where id like 'demo-%';",
  "--   delete from public.announcements where slug like 'demo-%';",
  "begin;",
  "",
  `insert into public.opponents (id, name, short_name) values\n${values(opponents)}\non conflict (id) do nothing;`,
  "",
];

for (const game of games) {
  const manual = Boolean(game.manualScore);
  demo.push(
    `insert into public.games (id, season_id, team_id, opponent_id, is_home, starts_at, location, status, scoring_mode, team_score, opponent_score, current_period, clock_seconds_left) values\n` +
      `  (${sql(game.id)}, ${sql(season.id)}, ${sql(game.team)}, ${sql(game.opponent)}, ${game.isHome}, ${startsAtSql(game)}, ${sql(game.location)}, ${sql(game.status)}, ${sql(manual ? "manual" : "live")}, ${game.manualScore?.[0] ?? 0}, ${game.manualScore?.[1] ?? 0}, ${game.clock?.period ?? 1}, ${game.clock?.secondsLeft ?? 480})\n` +
      "on conflict (id) do nothing;",
  );

  if (game.events.length) {
    const rows = game.events.map(
      (event) =>
        `  (${sql(game.id)}, ${sql(event.side)}, ${sql(event.athlete_id)}, ${sql(event.event_type)}, ${event.period}, ${event.clock_seconds_left}, ${sql(event.shot_x)}, ${sql(event.shot_y)}, ${startsAtSql(game)} + interval '${event.offset_seconds} seconds')`,
    );
    demo.push(
      `insert into public.game_events (game_id, side, athlete_id, event_type, period, clock_seconds_left, shot_x, shot_y, created_at) values\n${rows.join(",\n")};`,
    );
  }
  demo.push("");
}

